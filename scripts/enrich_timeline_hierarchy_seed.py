def load_json(path: pathlib.Path) -> object:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def build_ref_index(verse_order: dict) -> tuple[dict[str, int], dict[str, str], dict[str, str]]:
    refs: dict[str, int] = {}
    chapter_first: dict[str, str] = {}
    chapter_last: dict[str, str] = {}
    for verse in verse_order["verses"]:
        refs[verse["ref"]] = verse["sequence"]
        chapter_ref = f"{verse['book']} {verse['chapter']}"
        chapter_first.setdefault(chapter_ref, verse["ref"])
        chapter_last[chapter_ref] = verse["ref"]
    return refs, chapter_first, chapter_last


def resolve_ref_anchor(ref: str, chapter_first: dict[str, str], chapter_last: dict[str, str], *, edge: str) -> str:
    if ":" in ref:
        return ref
    if edge == "start" and ref in chapter_first:
        return chapter_first[ref]
    if edge == "end" and ref in chapter_last:
        return chapter_last[ref]
    return ref


def annotate_sequences(
    event: dict,
    ref_index: dict[str, int],
    chapter_first: dict[str, str],
    chapter_last: dict[str, str],
) -> None:
    start_ref = event.get("startRef")
    end_ref = event.get("endRef")
    if isinstance(start_ref, str):
        start_ref = resolve_ref_anchor(start_ref, chapter_first, chapter_last, edge="start")
        event["startRef"] = start_ref
        event["startSequence"] = ref_index[start_ref]
    if isinstance(end_ref, str):
        end_ref = resolve_ref_anchor(end_ref, chapter_first, chapter_last, edge="end")
        event["endRef"] = end_ref
        event["endSequence"] = ref_index[end_ref]

    for child in event.get("children", []):
        annotate_sequences(child, ref_index, chapter_first, chapter_last)


def apply_curated_children(event: dict) -> None:
    if event["id"] in EVENT_CHILDREN:
        event["children"] = EVENT_CHILDREN[event["id"]]

    for child in event.get("children", []):
        apply_curated_children(child)


def main() -> int:
    if len(sys.argv) != 3:
        print(
            "Usage: python3 scripts/enrich_timeline_hierarchy_seed.py <hierarchy.json> <verse-order.json>",
            file=sys.stderr,
        )
        return 1

    hierarchy_path = pathlib.Path(sys.argv[1])
    verse_order_path = pathlib.Path(sys.argv[2])

    hierarchy = load_json(hierarchy_path)
    verse_order = load_json(verse_order_path)
    ref_index, chapter_first, chapter_last = build_ref_index(verse_order)

    for root_event in hierarchy["events"]:
        if root_event["id"] in ROOT_OVERRIDES:
            root_event.update(ROOT_OVERRIDES[root_event["id"]])
        if root_event["id"] in LEVEL1_CHILDREN:
            root_event["children"] = LEVEL1_CHILDREN[root_event["id"]]
        apply_curated_children(root_event)
        annotate_sequences(root_event, ref_index, chapter_first, chapter_last)

    hierarchy_path.write_text(json.dumps(hierarchy, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
